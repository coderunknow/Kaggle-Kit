#!/usr/bin/env python3
"""Build the notebook deliverable of a release from the deployment script.

The project ships the Kaggle deployment as a Python script
(``notebooks/qwen3_8_27b_api.py``). Kaggle accepts a notebook, so the release
contains a notebook that holds the script of the tagged commit in a single
code cell. The notebook is generated, never edited by hand, so that it always
matches the script in the repository.

The script refuses to build a notebook from a source that contains a literal
API key.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

# A literal key in the source would end up in the release archive.
SECRET_PATTERNS = (
    re.compile(r"""api[_-]?key\s*=\s*["'][^"']{16,}["']""", re.IGNORECASE),
    re.compile(r"""sk-[A-Za-z0-9_\-]{20,}"""),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
)

MARKDOWN = """# Kaggle-Kit - Qwen3 8/27B API on Kaggle

This notebook was generated by `tools/build_notebook.py` from
`notebooks/qwen3_8_27b_api.py` of the release commit `{source_sha}`.

Release: `{version}` (`{tag}`)

## What the cell does

1. Downloads and verifies the `llama.cpp` server binaries and the GGUF model.
2. Generates a random API key, stores it in `api_key.txt` (mode 0600) and
   restarts the server when the key or the configuration changes.
3. Starts a Cloudflare Quick Tunnel and verifies the public endpoint with a
   real chat completion before the URL is printed.
4. Stops the tunnel and the server at the end of the session.

## How to use it

1. Open the notebook in a Kaggle GPU runtime.
2. Run the cell. The output ends with the public URL and the API key file.
3. Use the URL as the base URL of the Kaggle-Kit application, the content of
   `api_key.txt` as the API key.

The Quick Tunnel is temporary: it is gone when the session ends and it does
not support server sent events. Use the non streaming mode of the
application.

## Limitations

The behaviour of the cell on a real Kaggle GPU runtime is verified by
Kaggle, not by this repository. The automated tests of this repository use
stubs and a mock server, they do not run a real model.
"""


def fail(message: str) -> "NoReturn":  # type: ignore[valid-type]
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--version", required=True)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--source-sha", required=True)
    args = parser.parse_args()

    if not args.source.is_file():
        fail(f"the source {args.source} does not exist")
    source = args.source.read_text(encoding="utf-8")
    if not source.strip():
        fail(f"the source {args.source} is empty")

    for pattern in SECRET_PATTERNS:
        if pattern.search(source):
            fail(f"the source {args.source} contains something that looks like a secret")

    cells = [
        {
            "cell_type": "markdown",
            "metadata": {},
            "source": MARKDOWN.format(
                source_sha=args.source_sha,
                version=args.version,
                tag=args.tag,
            ).splitlines(keepends=True),
        },
        {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": source.splitlines(keepends=True),
        },
    ]

    notebook = {
        "cells": cells,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {
                "name": "python",
                "version": "3.11",
                "file_extension": ".py",
                "mimetype": "text/x-python",
                "pygments_lexer": "ipython3",
            },
            "kaggle": {
                "kernelspec": "python3",
                "language": "python3",
            },
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as handle:
        json.dump(notebook, handle, indent=1, ensure_ascii=False)
        handle.write("\n")

    # The result has to be readable again.
    with args.output.open("r", encoding="utf-8") as handle:
        reloaded = json.load(handle)
    code_cells = [cell for cell in reloaded["cells"] if cell["cell_type"] == "code"]
    if len(code_cells) != 1 or "".join(code_cells[0]["source"]) != source:
        fail("the generated notebook does not contain the source unchanged")

    print(f"wrote {args.output} ({args.output.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
